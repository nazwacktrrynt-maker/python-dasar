a = 10
b = 3

# Operator aritmatika
print("Tambah:", a + b)
print("Kurang:", a - b)
print("Kali:", a * b)
print("Bagi:", a / b)
print("Bagi bulat:", a // b)
print("Sisa bagi:", a % b)
print("Pangkat:", a ** b)

# Operator perbandingan
print("a > b:", a > b)
print("a == b:", a == b)
print("a != b:", a != b)

# Operator logika
print("True and False:", True and False)
print("True or False:", True or False)
print("not True:", not True)